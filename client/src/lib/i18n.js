export function translate(lang, key, vars) {
  const table = dict[lang] || dict.en;
  let text = table[key] ?? dict.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replaceAll(`{${k}}`, String(v));
    });
  }
  return text;
}
